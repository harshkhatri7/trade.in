@dataclass(frozen=True, slots=True)
class OosTrack:
    """The out-of-sample segments aggregated, with every part kept visible.

    Attributes:
        windows: Number of test segments (>= 1).
        compounded_net_return: Product of ``1 + segment return`` minus
            1 — the documented full-re-deployment compounding.
        positive / negative / flat: Segment counts by sign (stability
            at a glance: how often the edge showed up at all).
        best_window / worst_window: Indices of the extreme segments
            (first occurrence on ties); the extremes are shown beside
            the aggregate so a single lucky segment cannot hide in an
            average.
        filled: Orders executed across all test segments.
        commission: Fees paid across all test segments.
        round_trips / wins / losses / breakeven: Pooled completed
            cycles under §4's rules.
        hit_rate: ``wins / (wins + losses)`` pooled; ``None`` when no
            cycle completed (nothing to hit).
        wilson_low / wilson_high: Wilson 95% interval for the pooled
            hit rate; ``None`` when there are no trials.
        open_at_end_windows: Segments that ended holding a position —
            their outcome is not in the round-trip counts.
        variants_tried: Total training-slice evaluations across all
            windows — the multiple-testing denominator.
    """

    windows: int
    compounded_net_return: Decimal
    positive: int
    negative: int
    flat: int
    best_window: int
    best_return: Decimal
    worst_window: int
    worst_return: Decimal
    filled: int
    commission: Decimal
    round_trips: int
    wins: int
    losses: int
    breakeven: int
    hit_rate: Decimal | None
    wilson_low: Decimal | None
    wilson_high: Decimal | None
    open_at_end_windows: int
    variants_tried: int


