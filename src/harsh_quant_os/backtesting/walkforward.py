def _canonical(payload: object) -> str:
    # Same canonical form as manifest_to_json: byte-identical across
    # builds, keys sorted, ASCII only.
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def _need(mapping: dict[str, object], key: str, where: str) -> object:
    if key not in mapping:
        raise BacktestError(f"walk-forward summary is missing {where}.{key}")
    return mapping[key]


def _as_text(value: object, where: str) -> str:
    if not isinstance(value, str):
        raise BacktestError(f"{where} must be a string, got {type(value).__name__}")
    return value


def _as_int(value: object, where: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise BacktestError(f"{where} must be an integer, got {type(value).__name__}")
    return value


def _as_bool(value: object, where: str) -> bool:
    if not isinstance(value, bool):
        raise BacktestError(f"{where} must be true or false, got {type(value).__name__}")
    return value


def _as_decimal(value: object, where: str) -> Decimal:
    text = _as_text(value, where)
    try:
        parsed = Decimal(text)
    except (InvalidOperation, ValueError) as error:
        raise BacktestError(f"{where} is not a decimal number: {text!r}") from error
    if not parsed.is_finite():
        raise BacktestError(f"{where} must be finite, got {text!r}")
    return parsed


def _as_time(value: object, where: str) -> datetime:
    text = _as_text(value, where)
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError as error:
        raise BacktestError(f"{where} is not an ISO timestamp: {text!r}") from error
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise BacktestError(
            f"{where} must be timezone-aware (the engine's bar timestamps are): got {text!r}"
        )
    return parsed


def _as_mapping(value: object, where: str) -> dict[str, object]:
    if not isinstance(value, dict):
        raise BacktestError(f"{where} must be a JSON object, got {type(value).__name__}")
    return cast(dict[str, object], value)


def _as_list(value: object, where: str) -> list[object]:
    if not isinstance(value, list):
        raise BacktestError(f"{where} must be a JSON array, got {type(value).__name__}")
    return value


def _window_from(mapping: dict[str, object], where: str) -> WalkForwardWindow:
    train = _as_mapping(_need(mapping, "train", where), f"{where}.train")
    test = _as_mapping(_need(mapping, "test", where), f"{where}.test")
    return WalkForwardWindow(
        index=_as_int(_need(mapping, "index", where), f"{where}.index"),
        train_index=_as_int(_need(mapping, "train_index", where), f"{where}.train_index"),
        train_bars=_as_int(_need(train, "bars", f"{where}.train"), f"{where}.train.bars"),
        train_start=_as_time(_need(train, "start", f"{where}.train"), f"{where}.train.start"),
        train_end=_as_time(_need(train, "end", f"{where}.train"), f"{where}.train.end"),
        test_index=_as_int(_need(mapping, "test_index", where), f"{where}.test_index"),
        test_bars=_as_int(_need(test, "bars", f"{where}.test"), f"{where}.test.bars"),
        test_start=_as_time(_need(test, "start", f"{where}.test"), f"{where}.test.start"),
        test_end=_as_time(_need(test, "end", f"{where}.test"), f"{where}.test.end"),
    )


def _numbers_from(mapping: dict[str, object], where: str) -> OutOfSampleNumbers:
    return OutOfSampleNumbers(
        net_return=_as_decimal(_need(mapping, "net_return", where), f"{where}.net_return"),
        ending_equity=_as_decimal(_need(mapping, "ending_equity", where), f"{where}.ending_equity"),
        filled=_as_int(_need(mapping, "filled", where), f"{where}.filled"),
        round_trips=_as_int(_need(mapping, "round_trips", where), f"{where}.round_trips"),
        wins=_as_int(_need(mapping, "wins", where), f"{where}.wins"),
        losses=_as_int(_need(mapping, "losses", where), f"{where}.losses"),
        breakeven=_as_int(_need(mapping, "breakeven", where), f"{where}.breakeven"),
        open_at_end=_as_bool(_need(mapping, "open_at_end", where), f"{where}.open_at_end"),
        commission=_as_decimal(_need(mapping, "commission", where), f"{where}.commission"),
    )


def _selection_from(mapping: dict[str, object], where: str) -> SelectionTrace:
    runs_raw = _as_list(_need(mapping, "train_runs", where), f"{where}.train_runs")
    runs: list[CandidateRun] = []
    for position, entry in enumerate(runs_raw):
        entry_where = f"{where}.train_runs[{position}]"
        run = _as_mapping(entry, entry_where)
        manifest = _as_mapping(_need(run, "manifest", entry_where), f"{entry_where}.manifest")
        recorded = manifest.get("run_id")
        if recorded is None or compute_run_id(manifest) != _as_text(
            recorded, f"{entry_where}.manifest.run_id"
        ):
            raise BacktestError(
                f"{entry_where}: manifest run_id does not match its own payload "
                "(the summary has been altered since it was written)"
            )
        runs.append(
            CandidateRun(
                label=_as_text(_need(run, "label", entry_where), f"{entry_where}.label"),
                score=_as_decimal(_need(run, "score", entry_where), f"{entry_where}.score"),
                manifest=manifest,
            )
        )
    tied = tuple(
        _as_text(entry, f"{where}.tied[{position}]")
        for position, entry in enumerate(_as_list(_need(mapping, "tied", where), f"{where}.tied"))
    )
    return SelectionTrace(
        selected=_as_text(_need(mapping, "selected", where), f"{where}.selected"),
        tied=tied,
        objective=_as_text(_need(mapping, "objective", where), f"{where}.objective"),
        runs=tuple(runs),
    )


def _outcome_from(mapping: dict[str, object], where: str) -> WindowOutcome:
    manifest = _as_mapping(_need(mapping, "manifest", where), f"{where}.manifest")
    recorded = manifest.get("run_id")
    if recorded is None or compute_run_id(manifest) != _as_text(
        recorded, f"{where}.manifest.run_id"
    ):
        raise BacktestError(
            f"{where}.manifest: run_id does not match its own payload "
            "(the summary has been altered since it was written)"
        )
    return WindowOutcome(
        window=_window_from(
            _as_mapping(_need(mapping, "window", where), f"{where}.window"),
            f"{where}.window",
        ),
        selection=_selection_from(
            _as_mapping(_need(mapping, "selection", where), f"{where}.selection"),
            f"{where}.selection",
        ),
        out_of_sample=_numbers_from(
            _as_mapping(_need(mapping, "out_of_sample", where), f"{where}.out_of_sample"),
            f"{where}.out_of_sample",
        ),
        manifest=manifest,
    )


def _track_from(mapping: dict[str, object], where: str) -> OosTrack:
    best = _as_mapping(_need(mapping, "best", where), f"{where}.best")
    worst = _as_mapping(_need(mapping, "worst", where), f"{where}.worst")
    hit_rate_raw = _need(mapping, "hit_rate", where)
    wilson_raw = _need(mapping, "wilson_95", where)
    hit_rate = None if hit_rate_raw is None else _as_decimal(hit_rate_raw, f"{where}.hit_rate")
    if wilson_raw is None:
        wilson: tuple[Decimal, Decimal] | None = None
    else:
        bounds = _as_list(wilson_raw, f"{where}.wilson_95")
        if len(bounds) != 2:
            raise BacktestError(
                f"{where}.wilson_95 must hold exactly two bounds, got {len(bounds)}"
            )
        wilson = (
            _as_decimal(bounds[0], f"{where}.wilson_95[0]"),
            _as_decimal(bounds[1], f"{where}.wilson_95[1]"),
        )
    return OosTrack(
        windows=_as_int(_need(mapping, "windows", where), f"{where}.windows"),
        compounded_net_return=_as_decimal(
            _need(mapping, "compounded_net_return", where),
            f"{where}.compounded_net_return",
        ),
        positive=_as_int(_need(mapping, "positive", where), f"{where}.positive"),
        negative=_as_int(_need(mapping, "negative", where), f"{where}.negative"),
        flat=_as_int(_need(mapping, "flat", where), f"{where}.flat"),
        best_window=_as_int(_need(best, "window", f"{where}.best"), f"{where}.best.window"),
        best_return=_as_decimal(_need(best, "return", f"{where}.best"), f"{where}.best.return"),
        worst_window=_as_int(_need(worst, "window", f"{where}.worst"), f"{where}.worst.window"),
        worst_return=_as_decimal(_need(worst, "return", f"{where}.worst"), f"{where}.worst.return"),
        filled=_as_int(_need(mapping, "filled", where), f"{where}.filled"),
        commission=_as_decimal(_need(mapping, "commission", where), f"{where}.commission"),
        round_trips=_as_int(_need(mapping, "round_trips", where), f"{where}.round_trips"),
        wins=_as_int(_need(mapping, "wins", where), f"{where}.wins"),
        losses=_as_int(_need(mapping, "losses", where), f"{where}.losses"),
        breakeven=_as_int(_need(mapping, "breakeven", where), f"{where}.breakeven"),
        hit_rate=hit_rate,
        wilson_low=None if wilson is None else wilson[0],
        wilson_high=None if wilson is None else wilson[1],
        open_at_end_windows=_as_int(
            _need(mapping, "open_at_end_windows", where), f"{where}.open_at_end_windows"
        ),
        variants_tried=_as_int(_need(mapping, "variants_tried", where), f"{where}.variants_tried"),
    )


def _track_payload(track: OosTrack) -> dict[str, object]:
    hit_rate: object = None if track.hit_rate is None else str(track.hit_rate)
    wilson: object = (
        None
        if track.wilson_low is None or track.wilson_high is None
        else [str(track.wilson_low), str(track.wilson_high)]
    )
    return {
        "windows": track.windows,
        "compounded_net_return": str(track.compounded_net_return),
        "positive": track.positive,
        "negative": track.negative,
        "flat": track.flat,
        "best": {"window": track.best_window, "return": str(track.best_return)},
        "worst": {"window": track.worst_window, "return": str(track.worst_return)},
        "filled": track.filled,
        "commission": str(track.commission),
        "round_trips": track.round_trips,
        "wins": track.wins,
        "losses": track.losses,
        "breakeven": track.breakeven,
        "hit_rate": hit_rate,
        "wilson_95": wilson,
        "open_at_end_windows": track.open_at_end_windows,
        "variants_tried": track.variants_tried,
    }


def _numbers_payload(numbers: OutOfSampleNumbers) -> dict[str, object]:
    return {
        "net_return": str(numbers.net_return),
        "ending_equity": str(numbers.ending_equity),
        "filled": numbers.filled,
        "round_trips": numbers.round_trips,
        "wins": numbers.wins,
        "losses": numbers.losses,
        "breakeven": numbers.breakeven,
        "open_at_end": numbers.open_at_end,
        "commission": str(numbers.commission),
    }


def _time_payload(value: datetime) -> str:
    return value.isoformat()


# Attach the JSON surface to the summary (kept beside the class so the
# dataclass above stays a plain record).
def _summary_to_json(summary: WalkForwardSummary) -> str:
    windows: list[object] = []
    for outcome in summary.outcomes:
        window = outcome.window
        trace = outcome.selection
        windows.append(
            {
                "window": {
                    "index": window.index,
                    "train_index": window.train_index,
                    "test_index": window.test_index,
                    "train": {
                        "start": _time_payload(window.train_start),
                        "end": _time_payload(window.train_end),
                        "bars": window.train_bars,
                    },
                    "test": {
                        "start": _time_payload(window.test_start),
                        "end": _time_payload(window.test_end),
                        "bars": window.test_bars,
                    },
                },
                "selection": {
                    "selected": trace.selected,
                    "tied": list(trace.tied),
                    "objective": trace.objective,
                    "train_runs": [
                        {
                            "label": run.label,
                            "score": str(run.score),
                            "manifest": run.manifest,
                        }
                        for run in trace.runs
                    ],
                },
                "out_of_sample": _numbers_payload(outcome.out_of_sample),
                "manifest": outcome.manifest,
            }
        )
    payload: dict[str, object] = {
        "kind": "walk_forward",
        "summary_version": SUMMARY_VERSION,
        "dataset": {"id": summary.dataset_id, "version": summary.dataset_version},
        "layout": {
            "train_bars": summary.train_bars,
            "test_bars": summary.test_bars,
            "step_bars": summary.step_bars,
            "expanding": summary.expanding,
        },
        "objective": summary.objective,
        "candidates": list(summary.candidates),
        "notes": list(_NOTES),
        "windows": windows,
        "out_of_sample_track": _track_payload(summary.track),
    }
    return _canonical(payload)


def _summary_from_json(text: str) -> WalkForwardSummary:
    try:
        parsed: object = json.loads(text)
    except ValueError as error:
        raise BacktestError(f"walk-forward summary is not valid JSON: {error}") from error
    root = _as_mapping(parsed, "walk-forward summary")
    kind = _as_text(_need(root, "kind", "summary"), "summary.kind")
    if kind != "walk_forward":
        raise BacktestError(
            f"not a walk-forward summary (kind={kind!r}); refusing to read it as one"
        )
    version = _as_int(_need(root, "summary_version", "summary"), "summary.summary_version")
    if version != SUMMARY_VERSION:
        raise BacktestError(
            f"summary_version {version} is not what this build understands "
            f"({SUMMARY_VERSION}); refusing to guess its layout"
        )
    dataset = _as_mapping(_need(root, "dataset", "summary"), "summary.dataset")
    layout = _as_mapping(_need(root, "layout", "summary"), "summary.layout")

    stored_notes = tuple(
        _as_text(entry, f"summary.notes[{position}]")
        for position, entry in enumerate(_as_list(_need(root, "notes", "summary"), "summary.notes"))
    )
    if stored_notes != _NOTES:
        raise BacktestError(
            "the summary's honesty notes do not match this build's: the file "
            "has been altered or written by another version"
        )

    candidates = tuple(
        _as_text(entry, f"summary.candidates[{position}]")
        for position, entry in enumerate(
            _as_list(_need(root, "candidates", "summary"), "summary.candidates")
        )
    )
    outcomes = tuple(
        _outcome_from(
            _as_mapping(entry, f"summary.windows[{position}]"),
            f"summary.windows[{position}]",
        )
        for position, entry in enumerate(
            _as_list(_need(root, "windows", "summary"), "summary.windows")
        )
    )
    summary = WalkForwardSummary(
        dataset_id=_as_text(_need(dataset, "id", "summary.dataset"), "summary.dataset.id"),
        dataset_version=_as_text(
            _need(dataset, "version", "summary.dataset"), "summary.dataset.version"
        ),
        train_bars=_as_int(
            _need(layout, "train_bars", "summary.layout"), "summary.layout.train_bars"
        ),
        test_bars=_as_int(_need(layout, "test_bars", "summary.layout"), "summary.layout.test_bars"),
        step_bars=_as_int(_need(layout, "step_bars", "summary.layout"), "summary.layout.step_bars"),
        expanding=_as_bool(
            _need(layout, "expanding", "summary.layout"), "summary.layout.expanding"
        ),
        objective=_as_text(_need(root, "objective", "summary"), "summary.objective"),
        candidates=candidates,
        outcomes=outcomes,
    )

    # The aggregate must equal what the windows it claims to
    # summarise actually produce — a tampered track is a lie, not a
    # formatting choice.
    stored_track = _track_from(
        _as_mapping(_need(root, "out_of_sample_track", "summary"), "summary.out_of_sample_track"),
        "summary.out_of_sample_track",
    )
    if stored_track != summary.track:
        raise BacktestError(
            "out_of_sample_track does not match the windows it summarises "
            "(the summary has been altered since it was written)"
        )
    return summary
