@dataclass(frozen=True, slots=True)
class WalkForwardWindow:
    """One train-then-test span of a walk-forward, by bar position.

    Attributes:
        index: Window number, starting at 0, in generation order.
        train_index / train_bars: Training slice position and size.
        train_start / train_end: First and last training bar
            timestamps (inclusive).
        test_index / test_bars: Held-out slice position and size —
            always ``train_index + train_bars`` (the slices are
            adjacent; the test never overlaps its own training data).
        test_start / test_end: First and last test bar timestamps.
    """

    index: int
    train_index: int
    train_bars: int
    train_start: datetime
    train_end: datetime
    test_index: int
    test_bars: int
    test_start: datetime
    test_end: datetime

    def __post_init__(self) -> None:
        if self.index < 0 or self.train_index < 0:
            raise BacktestError("window index and train position are non-negative")
        if self.train_bars < 1 or self.test_bars < 1:
            raise BacktestError(
                "a window carries at least one training and one test bar; got "
                f"train_bars={self.train_bars}, test_bars={self.test_bars}"
            )
        if self.test_index != self.train_index + self.train_bars:
            raise BacktestError(
                "a window's test slice must start exactly where its training "
                f"slice ends (train [{self.train_index}, "
                f"{self.train_index + self.train_bars}), test at "
                f"{self.test_index}): a gap would hide data and an overlap "
                "would leak it"
            )
        if self.train_start > self.train_end:
            raise BacktestError("training span runs backwards")
        if self.train_end >= self.test_start:
            raise BacktestError(
                "the test slice must start strictly after every training bar "
                f"(train ends {self.train_end.isoformat()}, test starts "
                f"{self.test_start.isoformat()}): overlap would leak the "
                "answer into the selection"
            )
        if self.test_start > self.test_end:
            raise BacktestError("test span runs backwards")


def walk_forward_windows(
    data: BacktestData,
    *,
    train: int,
    test: int,
    step: int,
    expanding: bool = False,
) -> tuple[WalkForwardWindow, ...]:
    """Generate the train-then-test windows for a dataset.

    Args:
        data: The pinned dataset; windows are positions in its stored
            chronological order.
        train: Training slice size in bars (rolling windows).
        test: Test slice size in bars.
        step: Bars the window start advances between windows.
        expanding: When true, every window's training slice starts at
            bar 0 and grows with the step (expanding window).

    Returns:
        The windows in index order. At least one always fits, or
        :class:`BacktestError` is raised — a walk-forward that does
        not exist is refused, not reported as empty.

    Raises:
        BacktestError: Non-positive layout numbers, or
            ``train + test`` larger than the dataset.
    """
    if train < 1 or test < 1 or step < 1:
        raise BacktestError(
            f"window layout takes positive bar counts; got train={train}, test={test}, step={step}"
        )
    count = len(data.bars)
    if train + test > count:
        raise BacktestError(
            f"no walk-forward window fits: {count} bars cannot hold "
            f"train={train} + test={test}; refusing to report a "
            "walk-forward that does not exist"
        )
    windows: list[WalkForwardWindow] = []
    index = 0
    while True:
        test_index = index * step + train
        if test_index + test > count:
            break
        train_index = 0 if expanding else index * step
        bars = data.bars
        windows.append(
            WalkForwardWindow(
                index=index,
                train_index=train_index,
                train_bars=test_index - train_index,
                train_start=bars[train_index].timestamp,
                train_end=bars[test_index - 1].timestamp,
                test_index=test_index,
                test_bars=test,
                test_start=bars[test_index].timestamp,
                test_end=bars[test_index + test - 1].timestamp,
            )
        )
        index += 1
    return tuple(windows)


