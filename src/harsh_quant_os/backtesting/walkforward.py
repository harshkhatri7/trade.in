"""Walk-forward analysis: select on the past, evaluate on what follows.

Implements backtesting.md §3's walk-forward row and anti-overfitting
§2.3: rolling (or expanding) windows, candidates re-selected inside
each window's training slice, results aggregated across the windows'
out-of-sample segments — a single in-sample fit is never the headline.

Construction, stated so a reader cannot mistake it for anything else:

- Windows are generated by bar position on the pinned dataset:
  ``train`` bars of selection data followed immediately by ``test``
  bars of evaluation data, advancing ``step`` bars at a time
  (``expanding=True`` grows the training slice from bar 0 instead of
  rolling it). Test bars always start strictly after their own
  window's training bars — no look-ahead within a window.
- Each window is an **independent simulation**: fresh capital, fresh
  strategy instance, fresh risk evaluator; no position or ledger
  state carries between segments.
- Later windows' training slices **do contain** earlier windows'
  test segments — they are past data by then. This is the standard
  walk-forward construction, recorded in the summary's notes so it
  can never be read as one global hold-out. The held-out-once
  protocol lives in :mod:`~harsh_quant_os.backtesting.validation`.
- The out-of-sample track **compounds** each segment's net return as
  if the full capital were re-deployed at each segment start; pooled
  trade counts are summed across segments. Every per-window number is
  kept beside the aggregate — the surface, not the optimum
  (anti-overfitting §2.4).

Every run — each candidate on each training slice, each selected
strategy on each test slice — carries its own §3 manifest inside the
summary, so the whole analysis is replayable from stored JSON
(:meth:`WalkForwardSummary.to_json` / :func:`WalkForwardSummary.
from_json`), which refuses tampered or structurally inconsistent
summaries before they can be believed.
"""

