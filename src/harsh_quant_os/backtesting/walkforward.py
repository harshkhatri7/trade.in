@dataclass(frozen=True, slots=True)
class WalkForwardSummary:
    """One complete walk-forward, stored the way it can be replayed.

    Attributes:
        dataset_id / dataset_version: The pinned input.
        train_bars / test_bars / step_bars / expanding: The layout
            that generated ``outcomes``.
        objective: The ranking objective's recorded name.
        candidates: Declared labels, in declared order — the race
            every window ran.
        outcomes: One per window, in index order (at least one).
    """

    dataset_id: str
    dataset_version: str
    train_bars: int
    test_bars: int
    step_bars: int
    expanding: bool
    objective: str
    candidates: tuple[str, ...]
    outcomes: tuple[WindowOutcome, ...]

    def __post_init__(self) -> None:
        if not self.candidates:
            raise BacktestError("a walk-forward declares at least one candidate")
        if len(set(self.candidates)) != len(self.candidates):
            raise BacktestError("candidate labels must be distinct to be recordable")
        if not self.objective.strip():
            raise BacktestError("a summary records the objective its windows ranked under")
        if not self.outcomes:
            raise BacktestError("a walk-forward summary carries at least one window")
        for position, outcome in enumerate(self.outcomes):
            if outcome.window.index != position:
                raise BacktestError(
                    "window outcomes must arrive in index order; got "
                    f"position {position} holding index {outcome.window.index}"
                )
            if outcome.selection.objective != self.objective:
                raise BacktestError(
                    f"window {position} ranked under {outcome.selection.objective!r}, "
                    f"the summary records {self.objective!r}"
                )
            raced = tuple(run.label for run in outcome.selection.runs)
            if raced != self.candidates:
                raise BacktestError(
                    f"window {position} raced {raced!r}, but the summary declares "
                    f"{self.candidates!r}: every window must race the same "
                    "declared candidates in the same order"
                )
            # Evidence that disagrees with the layout it claims to come
            # from is refused — in memory as well as from JSON.
            _verify_manifest_bounds(
                f"window {position}'s test manifest",
                outcome.manifest,
                start=outcome.window.test_start,
                end=outcome.window.test_end,
            )
            for run in outcome.selection.runs:
                _verify_manifest_bounds(
                    f"window {position}'s {run.label!r} train manifest",
                    run.manifest,
                    start=outcome.window.train_start,
                    end=outcome.window.train_end,
                )

    @property
    def track(self) -> OosTrack:
        """The out-of-sample segments aggregated from the windows."""
        returns = [outcome.out_of_sample.net_return for outcome in self.outcomes]
        compounded = Decimal(1)
        for value in returns:
            compounded *= Decimal(1) + value
        compounded -= Decimal(1)

        best = max(returns)
        worst = min(returns)
        trials = 0
        wins = 0
        losses = 0
        breakeven = 0
        for outcome in self.outcomes:
            trials += outcome.out_of_sample.wins + outcome.out_of_sample.losses
            wins += outcome.out_of_sample.wins
            losses += outcome.out_of_sample.losses
            breakeven += outcome.out_of_sample.breakeven
        interval = wilson_interval(wins, trials)
        hit_rate = (Decimal(wins) / Decimal(trials)) if trials else None
        return OosTrack(
            windows=len(self.outcomes),
            compounded_net_return=compounded,
            positive=sum(1 for value in returns if value > 0),
            negative=sum(1 for value in returns if value < 0),
            flat=sum(1 for value in returns if value == 0),
            best_window=returns.index(best),
            best_return=best,
            worst_window=returns.index(worst),
            worst_return=worst,
            filled=sum(o.out_of_sample.filled for o in self.outcomes),
            commission=sum((o.out_of_sample.commission for o in self.outcomes), Decimal(0)),
            round_trips=sum(o.out_of_sample.round_trips for o in self.outcomes),
            wins=wins,
            losses=losses,
            breakeven=breakeven,
            hit_rate=hit_rate,
            wilson_low=interval[0] if interval else None,
            wilson_high=interval[1] if interval else None,
            open_at_end_windows=sum(1 for o in self.outcomes if o.out_of_sample.open_at_end),
            variants_tried=len(self.candidates) * len(self.outcomes),
        )

    def to_json(self) -> str:
        """Canonical JSON text for storage (byte-identical across builds)."""
        return _summary_to_json(self)

    @staticmethod
    def from_json(text: str) -> WalkForwardSummary:
        """Parse stored JSON, refusing anything altered or mis-laid-out.

        Raises:
            BacktestError: Not JSON / not an object, wrong ``kind``,
                unknown ``summary_version``, missing or ill-typed
                fields, notes edited away, any embedded manifest whose
                ``run_id`` no longer matches its own payload, or an
                out-of-sample track that does not match the windows it
                claims to summarise.
        """
        return _summary_from_json(text)


def walk_forward(
    data: BacktestData,
    *,
    candidates: Sequence[Candidate],
    config: BacktestConfig,
    risk_factory: Callable[[], RiskEvaluator],
    train: int,
    test: int,
    step: int,
    expanding: bool = False,
    objective: SelectionObjective = ENDING_EQUITY,
) -> WalkForwardSummary:
    """Run a full walk-forward: select inside each window, test after it.

    Args:
        data: The pinned dataset.
        candidates: Declared variants; each run gets a fresh
            instance from its builder and a fresh risk evaluator.
        config: Capital and cost models, identical across all runs.
        risk_factory: Builds one fresh evaluator per run — evaluators
            are per-run objects and must not carry state between
            windows.
        train / test / step: The window layout (see
            :func:`walk_forward_windows`).
        expanding: Expanding instead of rolling training slices.
        objective: The ranking rule, recorded by name.

    Returns:
        The summary: per-window selection traces, out-of-sample
        numbers, every run's manifest, and the aggregated track.

    Raises:
        BacktestError: No candidates, duplicate labels, a layout with
            no window that fits, or a train/test segment shorter than
            the engine's two-bar floor.
    """
    if not candidates:
        raise BacktestError("a walk-forward needs at least one candidate")
    labels = tuple(candidate.label for candidate in candidates)
    if len(set(labels)) != len(labels):
        raise BacktestError(
            "candidate labels must be distinct: the trace names every variant "
            "it tried, and two identical labels cannot be told apart"
        )
    if train < 2 or test < 2:
        raise BacktestError(
            f"the engine decides on one bar and fills on the next, so every "
            f"train and test segment needs at least two bars; got train={train}, "
            f"test={test} (refusing to produce runs the engine cannot perform)"
        )
    by_label = {candidate.label: candidate for candidate in candidates}
    windows = walk_forward_windows(data, train=train, test=test, step=step, expanding=expanding)

    outcomes: list[WindowOutcome] = []
    for window in windows:
        train_slice = data.span(window.train_index, window.train_index + window.train_bars)
        test_slice = data.span(window.test_index, window.test_index + window.test_bars)
        trace = select_on_train(
            train_slice,
            candidates=candidates,
            config=config,
            risk_factory=risk_factory,
            objective=objective,
        )
        risk = risk_factory()
        strategy = by_label[trace.selected].fresh()
        result = run_backtest(test_slice, strategy, config, risk=risk)
        manifest = build_manifest(result, config=config, risk=risk)
        outcomes.append(
            WindowOutcome(
                window=window,
                selection=trace,
                out_of_sample=OutOfSampleNumbers.from_result(result),
                manifest=manifest,
            )
        )

    return WalkForwardSummary(
        dataset_id=data.dataset_id,
        dataset_version=data.version,
        train_bars=train,
        test_bars=test,
        step_bars=step,
        expanding=expanding,
        objective=objective.name,
        candidates=labels,
        outcomes=tuple(outcomes),
    )


def replay_walk_forward(
    root: Path,
    summary: WalkForwardSummary,
    *,
    builders: Mapping[str, Candidate],
    risk_factory: Callable[[], RiskEvaluator],
    objective: SelectionObjective = ENDING_EQUITY,
) -> tuple[BacktestResult, ...]:
    """Re-execute every manifest in a summary and re-derive its numbers.

    The stored evidence is worthless if nobody can run it again, so
    replay verifies, failing closed at the first mismatch:

    1. The caller's objective is the one the summary ranked under —
       scores cannot be re-derived under a different rule.
    2. Every declared candidate has a builder (the manifest proves the
       built strategy is the one that ran, field for field).
    3. Every manifest reproduces byte-for-byte: the pinned dataset is
       loaded, narrowed to the recorded window (exact bounds), run,
       and compared artefact by artefact
       (:func:`~harsh_quant_os.backtesting.manifest.run_from_manifest`).
    4. Every selection score re-derives from the reproduced run.
    5. Every window's out-of-sample numbers re-derive from the
       reproduced test run, exactly.

    Args:
        root: The data root holding ``clean/``.
        summary: The walk-forward summary (fresh or loaded from JSON).
        builders: ``label -> candidate`` for every declared candidate;
            builders for labels the summary does not declare are
            ignored.
        risk_factory: A **fresh** evaluator per run.
        objective: The ranking objective, matching the summary's.

    Returns:
        The reproduced out-of-sample results, one per window in index
        order.

    Raises:
        BacktestError: Objective mismatch, missing builder, a manifest
            that does not reproduce, a score that does not re-derive,
            or numbers that do not follow from their manifest.
        RecipeError: A pinned dataset version is absent or its stored
            hash no longer matches.
        ReproductionMismatch: A run executed but produced different
            artefacts.
    """
    if summary.objective != objective.name:
        raise BacktestError(
            f"the summary ranked under {summary.objective!r} but replay was "
            f"given objective {objective.name!r}: scores cannot be re-derived "
            "under a different rule than the one recorded"
        )
    missing = [label for label in summary.candidates if label not in builders]
    if missing:
        raise BacktestError(
            "no builder supplied for candidate(s) "
            + ", ".join(repr(label) for label in missing)
            + ": a run whose strategy cannot be rebuilt cannot be replayed"
        )

    replayed: list[BacktestResult] = []
    for outcome in summary.outcomes:
        index = outcome.window.index
        for run in outcome.selection.runs:
            result = run_from_manifest(
                root,
                run.manifest,
                strategy=builders[run.label].fresh(),
                risk=risk_factory(),
            )
            score = objective(result)
            if score != run.score:
                raise BacktestError(
                    f"window {index}: candidate {run.label!r} scored {run.score} "
                    f"in the summary but {score} on replay — the stored score "
                    "does not follow from the stored manifest"
                )
        test_result = run_from_manifest(
            root,
            outcome.manifest,
            strategy=builders[outcome.selection.selected].fresh(),
            risk=risk_factory(),
        )
        numbers = OutOfSampleNumbers.from_result(test_result)
        if numbers != outcome.out_of_sample:
            raise BacktestError(
                f"window {index}: out-of-sample numbers did not reproduce "
                f"(summary: {outcome.out_of_sample}, replay: {numbers}) — the "
                "stored evidence does not follow from the stored manifest"
            )
        replayed.append(test_result)
    return tuple(replayed)


